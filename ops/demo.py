"""Resettable demonstration environment (Phase 15).

    python -m ops.demo reset --data ./demo-data      # wipe that folder (only one this script created) and seed it again
    python -m ops.demo seed  --data ./demo-data      # seed into an empty folder

It always uses a local SQLite database inside --data and refuses to run when DATABASE_URL is set, so it can never touch
a shared or production database. The footage is synthetic, generated by `benchmark/` (owned by the project): there is no
licensed real footage yet (blocker B-7). Everything is created through the real API, so the demo exercises the same
code as production: analysis, review, rights verification, listing, a reservation, a campaign and a placement request.

Accounts (sign in with the magic link or code sent to the outbox folder, `<data>/outbox/latest.json`):
  admin@demo.visuara.si      platform administrator (Visuara Demo Ops)
  publisher@demo.visuara.si  owner of Demo Studio (publisher)
  brand@demo.visuara.si      owner of Demo Brand (brand)
"""
import argparse, hashlib, os, secrets, shutil, sys, time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path: sys.path.insert(0, str(ROOT))
MARKER = '.visuara-demo'
ACCOUNTS = {'admin': ('admin@demo.visuara.si', 'Visuara Demo Ops', 'direct'), 'publisher': ('publisher@demo.visuara.si', 'Demo Studio', 'publisher'),
            'brand': ('brand@demo.visuara.si', 'Demo Brand', 'brand')}
PDF = b'%PDF-1.4\n% Demonstration licence: synthetic footage generated by the Visuara benchmark, owned by the project.\n'


def _client(main):
    from fastapi.testclient import TestClient

    class C(TestClient):
        def request(self, method, url, **kw):
            if method.upper() not in ('GET', 'HEAD', 'OPTIONS'):
                h = dict(kw.pop('headers', None) or {}); tok = self.cookies.get('cc_csrf')
                if tok: h['x-csrf-token'] = tok
                kw['headers'] = h
            return super().request(method, url, **kw)
    return C(main.app)


def _login(main, c, email):
    c.cookies.clear(); token = secrets.token_urlsafe(32)
    with main.db() as con:
        uid = con.execute('SELECT id FROM users WHERE email=?', (email,)).fetchone()['id']
        con.execute('INSERT INTO sessions(token_hash,user_id,expires_at) VALUES(?,?,?)', (hashlib.sha256(token.encode()).hexdigest(), uid, int(time.time()) + 3600))
    c.cookies.set('cc_session', token); c.get('/api/auth/csrf')


def _ok(r, what):
    if r.status_code >= 400: raise SystemExit(f'Demo seeding failed at "{what}": {r.status_code} {r.text[:300]}')
    return r.json()


def seed(main, c, work):
    from app import members, intelligence
    from ops import platform_admin
    from benchmark import fixtures_scene as scene
    with main.db() as con:
        for key, (email, org, kind) in ACCOUNTS.items():
            oid = con.execute("INSERT INTO organizations(name,plan,kind) VALUES(?,'team',?)", (org, kind)).lastrowid
            uid = con.execute("INSERT INTO users(email,password_hash,name,role,org_id,member_role) VALUES(?,'',?,'brand',?,'owner')", (email, key.title(), oid)).lastrowid
            members.sync_membership(con, uid)
    platform_admin.set_flag(ACCOUNTS['admin'][0], True)
    _login(main, c, ACCOUNTS['publisher'][0])
    _ok(c.put('/api/profile', json={'display_name': 'Demo Studio', 'website': 'https://demo.visuara.si', 'categories': ['lifestyle', 'home']}), 'publisher profile')
    videos = []
    for seed_no in (1, 2):
        clip = scene.generate('room', seed_no, work / 'clips')
        v = _ok(c.post('/api/videos', data={'title': f'Living room, take {seed_no}', 'license_confirmed': 'true'},
                       files={'video': (Path(clip['path']).name, Path(clip['path']).read_bytes(), 'video/mp4')}), 'upload')
        _ok(c.post(f'/api/videos/{v["id"]}/analyses'), 'queue analysis'); videos.append(v['id'])
    while intelligence.run_next(): pass
    listed = []
    for vid in videos:
        rid = _ok(c.post(f'/api/videos/{vid}/rights', data={'holder': 'Demo Studio', 'expires_on': '2099-12-31'},
                         files={'evidence': ('demo-licence.pdf', PDF, 'application/pdf')}), 'rights')['id']
        _login(main, c, ACCOUNTS['admin'][0]); _ok(c.post(f'/api/admin/rights/{rid}/decision', json={'decision': 'VERIFIED', 'notes': 'demo footage'}), 'verify rights')
        _login(main, c, ACCOUNTS['publisher'][0])
        for item in _ok(c.get('/api/inventory'), 'inventory'):
            if item['video_id'] != vid: continue
            _ok(c.post(f'/api/opportunities/{item["opportunity_id"]}/review', json={'brand_safety': 'SAFE', 'notes': 'demo review'}), 'review')
            price = 25000 + int(item['opportunity']['feasibility_score'] * 50000) // 100 * 100
            _ok(c.post(f'/api/inventory/{item["id"]}/list', json={'price_minor': price, 'currency': 'EUR'}), 'list'); listed.append(item['id'])
    _login(main, c, ACCOUNTS['brand'][0])
    _ok(c.put('/api/profile', json={'display_name': 'Demo Brand', 'categories': ['tech'], 'excluded_terms': ['tobacco']}), 'brand profile')
    from benchmark import fixtures_scene as scene2
    img = scene2.product(work / 'sleeve.png', 160, 100, (180, 80, 30))
    pid = _ok(c.post('/api/products', data={'name': 'Laptop sleeve', 'category': 'tech'}, files={'image': ('sleeve.png', Path(img).read_bytes(), 'image/png')}), 'product')['id']
    camp = _ok(c.post('/api/campaigns', json={'name': 'Back to work', 'budget_minor': 200000, 'currency': 'EUR', 'objective': 'Desk and living-room placements'}), 'campaign')
    _ok(c.put(f'/api/campaigns/{camp["id"]}/products', json={'product_ids': [pid]}), 'campaign products')
    _ok(c.put(f'/api/campaigns/{camp["id"]}/targeting', json={'categories': ['tech']}), 'targeting')
    _ok(c.post(f'/api/campaigns/{camp["id"]}/transition', json={'to': 'SUBMITTED'}), 'submit')
    recs = _ok(c.get(f'/api/campaigns/{camp["id"]}/recommendations'), 'recommendations')['products'][0]['results']
    request = None
    if recs:
        res = _ok(c.post(f'/api/marketplace/inventory/{recs[0]["inventory_id"]}/reserve', json={'campaign_id': camp['id']}), 'reserve')
        request = _ok(c.post(f'/api/campaigns/{camp["id"]}/placement-requests', json={'reservation_id': res['id'], 'product_id': pid, 'notes': 'Demo request'}), 'request')['id']
    return {'videos': videos, 'listed_items': listed, 'product_id': pid, 'campaign_id': camp['id'], 'placement_request_id': request,
            'accounts': {k: v[0] for k, v in ACCOUNTS.items()}}


def main_cli(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('action', choices=('seed', 'reset')); ap.add_argument('--data', required=True)
    a = ap.parse_args(argv)
    if os.getenv('DATABASE_URL') or os.getenv('CC_DATABASE_URL'): raise SystemExit('Refusing to run: DATABASE_URL is set. The demo uses its own SQLite file only.')
    data = Path(a.data).resolve()
    if a.action == 'reset' and data.exists():
        if any(data.iterdir()) and not (data / MARKER).exists(): raise SystemExit(f'Refusing to reset {data}: it was not created by this script')
        shutil.rmtree(data)
    if data.exists() and any(data.iterdir()): raise SystemExit(f'{data} is not empty; use reset')
    data.mkdir(parents=True, exist_ok=True); (data / MARKER).write_text('created by ops/demo.py\n')
    os.environ.update({'CC_DATA_DIR': str(data), 'CC_DOTENV': '0', 'CC_INLINE_WORKER': '0', 'CC_MAIL_BACKEND': 'outbox', 'CC_DEFAULT_PLAN': 'team'})
    from app import main
    c = _client(main)
    with c:
        out = seed(main, c, data / 'work')
    print('Demo ready:', out)
    return out


if __name__ == '__main__':
    main_cli()
