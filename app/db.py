"""Database access for SQLite (local default) and PostgreSQL (Neon in production).

Application SQL is written once, in a portable subset of the SQLite dialect with `?` placeholders.
For PostgreSQL each statement is translated (placeholders, UTC timestamps, auto-generated ids) and cached.
Connections behave like sqlite3 connections used as context managers: commit on success, roll back on error,
then release (close for SQLite, return to the pool for PostgreSQL).
"""
import decimal, os, re, sqlite3, threading
from functools import lru_cache

try:
    import psycopg
    from psycopg_pool import ConnectionPool
    _PG_ERRORS = (psycopg.errors.IntegrityError,), (psycopg.OperationalError,)
except ImportError:          # SQLite-only installs do not need the PostgreSQL driver
    psycopg = None; ConnectionPool = None; _PG_ERRORS = (), ()

IntegrityError = (sqlite3.IntegrityError,) + _PG_ERRORS[0]
OperationalError = (sqlite3.OperationalError,) + _PG_ERRORS[1]

# SQLite's CURRENT_TIMESTAMP is UTC 'YYYY-MM-DD HH:MM:SS'; keep stored text identical on PostgreSQL.
_PG_NOW = "to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')"


def _outside_quotes(sql, fn):
    """Apply fn to the parts of sql that are not inside single-quoted literals."""
    parts = re.split(r"('(?:[^']|'')*')", sql)
    return ''.join(p if i % 2 else fn(p) for i, p in enumerate(parts))


def translate_ddl(script):
    def tr(s):
        s = re.sub(r'\b(\w+) INTEGER PRIMARY KEY\b', r'\1 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', s)
        s = re.sub(r'\bINTEGER\b', 'BIGINT', s)
        s = re.sub(r'\bREAL\b', 'DOUBLE PRECISION', s)
        return s.replace('CURRENT_TIMESTAMP', _PG_NOW)
    return _outside_quotes(script, tr)


def id_tables(script):
    """Tables whose primary key is a generated `id` column (INSERTs into them return the new id)."""
    return set(re.findall(r'CREATE TABLE IF NOT EXISTS (\w+)\(id INTEGER PRIMARY KEY', script))


@lru_cache(maxsize=2048)
def translate(sql, id_tabs):
    q = sql.replace('%', '%%')
    q = _outside_quotes(q, lambda s: s.replace('?', '%s').replace('CURRENT_TIMESTAMP', _PG_NOW))
    m = re.match(r'\s*INSERT INTO (\w+)', q, re.I)
    if m and m.group(1) in id_tabs and not re.search(r'\bRETURNING\b', q, re.I):
        q += ' RETURNING id'
    return q


class Row(tuple):
    """sqlite3.Row-compatible: row[0], row['col'], dict(row), row.keys()."""
    def __new__(cls, keys, values):
        r = super().__new__(cls, values); r._keys = keys; r._idx = {k: i for i, k in enumerate(keys)}; return r
    def __getitem__(self, k):
        return tuple.__getitem__(self, self._idx[k] if isinstance(k, str) else k)
    def keys(self): return list(self._keys)


def _value(v):
    if isinstance(v, decimal.Decimal): return int(v) if v == v.to_integral_value() else float(v)
    return v


def _param(v): return int(v) if isinstance(v, bool) else v


class _PgCursor:
    def __init__(self, cur, returning_id):
        self._cur = cur; self.rowcount = cur.rowcount; self.lastrowid = None
        if returning_id:
            r = cur.fetchone(); self.lastrowid = r[0] if r else None
    def _row(self, r):
        return None if r is None else Row([d.name for d in self._cur.description], [_value(v) for v in r])
    def fetchone(self): return self._row(self._cur.fetchone()) if self._cur.description else None
    def fetchall(self): return [self._row(r) for r in self._cur.fetchall()] if self._cur.description else []
    def __iter__(self): return iter(self.fetchall())


class Connection:
    kind = 'sqlite'
    def __init__(self, raw, release, id_tabs=frozenset()):
        self.raw = raw; self._release = release; self._id_tabs = id_tabs
    def execute(self, sql, params=()):
        if self.kind == 'sqlite': return self.raw.execute(sql, tuple(_param(p) for p in params))
        q = translate(sql, self._id_tabs)
        cur = self.raw.execute(q, tuple(_param(p) for p in params))
        return _PgCursor(cur, q.endswith(' RETURNING id') and not sql.rstrip().upper().endswith('RETURNING ID'))
    def executescript(self, script):
        if self.kind == 'sqlite': return self.raw.executescript(script)
        self.raw.execute(translate_ddl(script))
    def add_column(self, table, column, definition):
        if self.kind == 'sqlite':
            if column not in {r['name'] for r in self.raw.execute(f'PRAGMA table_info({table})').fetchall()}:
                self.raw.execute(f'ALTER TABLE {table} ADD COLUMN {column} {definition}')
        else:
            self.raw.execute(f'ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {column} {translate_ddl(definition)}')
    def columns(self, table):
        if self.kind == 'sqlite': return [r['name'] for r in self.raw.execute(f'PRAGMA table_info({table})').fetchall()]
        return [r[0] for r in self.raw.execute('SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=%s ORDER BY ordinal_position', (table,)).fetchall()]
    def tables(self):
        if self.kind == 'sqlite': return [r[0] for r in self.raw.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")]
        return [r[0] for r in self.raw.execute("SELECT table_name FROM information_schema.tables WHERE table_schema=current_schema() AND table_type='BASE TABLE' ORDER BY table_name")]
    def lock(self, key):
        """Serialise a critical section until this transaction ends (SQLite: database write lock; PostgreSQL: advisory lock)."""
        if self.kind == 'sqlite':
            # An open sqlite3 transaction already began with a write, so it holds the write lock.
            if not self.raw.in_transaction: self.raw.execute('BEGIN IMMEDIATE')
        else: self.raw.execute('SELECT pg_advisory_xact_lock(hashtext(%s))', (key,))
    def commit(self): self.raw.commit()
    def rollback(self): self.raw.rollback()
    def __enter__(self): return self
    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type is None: self.raw.commit()
            else: self.raw.rollback()
        finally:
            self._release()
        return False


class PgConnection(Connection):
    kind = 'postgres'


_POOLS = {}
_POOL_LOCK = threading.Lock()


def database_url():
    return os.getenv('DATABASE_URL') or os.getenv('CC_DATABASE_URL') or ''


def _pool(url, schema):
    key = (url, schema)
    with _POOL_LOCK:
        if key not in _POOLS:
            if psycopg is None: raise RuntimeError('DATABASE_URL is set but psycopg is not installed (pip install "psycopg[binary]" psycopg_pool)')
            kwargs = {'prepare_threshold': None, 'autocommit': False,   # no server-side prepares: safe behind Neon's pooler
                      'connect_timeout': int(os.getenv('CC_DB_CONNECT_TIMEOUT', '5')),
                      # Detect dead connections (network partition) instead of hanging on TCP retransmits for minutes.
                      'keepalives': 1, 'keepalives_idle': 30, 'keepalives_interval': 10, 'keepalives_count': 3,
                      'tcp_user_timeout': int(os.getenv('CC_DB_TCP_USER_TIMEOUT_MS', '20000'))}
            if schema: kwargs['options'] = f'-c search_path={schema}'
            # min_size=0 + max_idle: idle connections are closed, so an idle app lets Neon's compute scale to zero.
            _POOLS[key] = ConnectionPool(url, min_size=int(os.getenv('CC_DB_POOL_MIN', '0')), max_size=int(os.getenv('CC_DB_POOL_SIZE', '10')), kwargs=kwargs,
                                         check=ConnectionPool.check_connection, open=True, timeout=float(os.getenv('CC_DB_POOL_TIMEOUT', '10')),
                                         max_idle=float(os.getenv('CC_DB_POOL_MAX_IDLE', '60')), max_lifetime=float(os.getenv('CC_DB_POOL_MAX_LIFETIME', '1800')))
        return _POOLS[key]


def close_pools():
    with _POOL_LOCK:
        for p in _POOLS.values(): p.close()
        _POOLS.clear()


def connect(sqlite_path, url=None, schema=None, id_tabs=frozenset()):
    url = database_url() if url is None else url
    if url:
        pool = _pool(url, schema); raw = pool.getconn()
        return PgConnection(raw, lambda: pool.putconn(raw), id_tabs)
    raw = sqlite3.connect(sqlite_path, timeout=30); raw.row_factory = sqlite3.Row; raw.execute('PRAGMA foreign_keys=ON')
    return Connection(raw, raw.close)


def probe(sqlite_path, schema=None, url=None, timeout=5):
    """Readiness check with a short timeout, outside the pool (a pooled wait could take 30 s while the database is down)."""
    url = database_url() if url is None else url
    try:
        if url:
            with psycopg.connect(url, connect_timeout=timeout, autocommit=True, **({'options': f'-c search_path={schema}'} if schema else {})) as con:
                con.execute('SELECT 1').fetchone()
        else:
            with sqlite3.connect(sqlite_path, timeout=timeout) as con: con.execute('SELECT 1').fetchone()
        return True
    except Exception:
        return False


_REASONS = (   # (match 'any' or 'all' of these substrings of the driver's message, what to tell the operator); no hosts or credentials
    ('any', ('password authentication failed', 'authentication failed'), 'the database refused the password in DATABASE_URL. After a password reset, put the new connection string in the deployment\'s DATABASE_URL and redeploy'),
    ('any', ('could not translate host name', 'name or service not known', 'nodename nor servname', 'getaddrinfo failed'), 'the database host name in DATABASE_URL does not exist'),
    ('all', ('endpoint', 'disabled'), 'Neon refused the endpoint: check that the project and its compute are active and that DATABASE_URL is the current connection string'),
    ('all', ('endpoint', 'not found'), 'Neon does not know this endpoint: DATABASE_URL is from a deleted or different project'),
    ('all', ('quota', 'exceeded'), 'the Neon project is over its quota'),
    ('any', ('does not exist',), 'the database or role named in DATABASE_URL does not exist'),
    ('any', ('ssl', 'certificate'), 'the encrypted connection failed (check sslmode in DATABASE_URL)'),
    ('any', ('connection refused',), 'nothing is listening at the database address in DATABASE_URL'),
    ('any', ('timeout', 'timed out'), 'the database did not answer in time (Neon may be waking up, or the address is unreachable)'),
    ('any', ('too many connections', 'remaining connection slots'), 'the database has no free connections'),
)


def explain(exc):
    """A short, actionable reason for a connection failure. Safe to show in health checks: no hosts, users or secrets."""
    text = f'{type(exc).__name__} {exc}'.lower()
    for how, needles, reason in _REASONS:
        if (all if how == 'all' else any)(n in text for n in needles): return reason
    return f'the database connection failed ({type(exc).__name__})'


def diagnose(url=None, timeout=8):
    """Connect once outside the pool and return (ok, reason, detail). The pool's own timeout hides the driver's error;
    this gets it. `detail` is the driver's first line with any password removed, for logs only."""
    url = database_url() if url is None else url
    if not url: return True, '', ''
    try:
        with psycopg.connect(url, connect_timeout=timeout, autocommit=True) as con:
            con.execute('SELECT 1').fetchone()
        return True, '', ''
    except Exception as e:
        from .obs import redact
        first = (str(e).strip().splitlines() or [''])[0][:300]
        return False, explain(e), redact(f'{type(e).__name__}: {first}').replace(url, '[DATABASE_URL]')


def describe(url=None):
    url = database_url() if url is None else url
    if not url: return {'engine': 'sqlite'}
    host = re.sub(r'^.*@', '', url).split('/')[0].split('?')[0]
    return {'engine': 'postgres', 'host': host, 'neon': host.endswith('.neon.tech')}
