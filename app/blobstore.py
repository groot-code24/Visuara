"""Vercel Blob, private store: the object storage used when the whole platform runs on Vercel (BLOB_READ_WRITE_TOKEN).

Server-side reads and writes use Vercel's Python SDK. Two things that SDK does not offer are built here, byte for byte as
the official JavaScript SDK (@vercel/blob) does them, and tests/test_blob.py holds vectors generated by that SDK:
  * client_token: lets one browser upload one object directly to the store (Functions refuse bodies over 4.5 MB);
  * signed_url: a short-lived link to one private object, so videos stream from the CDN rather than through a Function.
"""
import base64, hashlib, hmac, json, os, threading, time
from pathlib import Path
from urllib.parse import quote, urlencode

import httpx

API_VERSION = '13'
MULTIPART_ABOVE = 64 * 1048576
PART_BYTES = 16 * 1048576
_RW_PREFIX = 'vercel_blob_rw_'
_delegation = {}
_lock = threading.Lock()


class BlobConfigError(RuntimeError):
    pass


def token(): return (os.getenv('BLOB_READ_WRITE_TOKEN') or '').strip()
def enabled(): return bool(token())
def api_url(): return (os.getenv('VERCEL_BLOB_API_URL') or 'https://vercel.com/api/blob').rstrip('/')


def store_id(rw_token=None):
    """The store id inside a read-write token: vercel_blob_rw_<store>_<secret>."""
    t = token() if rw_token is None else rw_token
    store, sep, secret = t[len(_RW_PREFIX):].partition('_')
    if not t.startswith(_RW_PREFIX) or not sep or not store or not secret:
        raise BlobConfigError('BLOB_READ_WRITE_TOKEN is not a Vercel Blob read-write token')
    return store


def delivery_url(pathname):
    return f'https://{store_id().lower()}.private.blob.vercel-storage.com/{quote(pathname, safe="/")}'


def _sdk():
    from vercel.blob import sync
    return sync


def put_file(pathname, path, content_type):
    """Store a local file, replacing any earlier copy. Large files go in parts, so memory use stays flat."""
    sdk = _sdk(); size = Path(path).stat().st_size
    if size <= MULTIPART_ABOVE:
        sdk.put_blob(pathname, Path(path).read_bytes(), access='private', content_type=content_type, allow_overwrite=True)
        return
    with sdk.multipart_upload_blob(pathname, access='private', content_type=content_type, allow_overwrite=True) as upload, open(path, 'rb') as f:
        while chunk := f.read(PART_BYTES):
            upload.upload_part(chunk)


def download(pathname, target):
    with _sdk().stream_blob(pathname, access='private') as body, open(target, 'wb') as f:
        for chunk in body:
            f.write(chunk)


def size(pathname):
    """Size in bytes, or None when the object does not exist or storage cannot be reached."""
    try: return int(_sdk().head_blob(pathname).size)
    except Exception: return None


def delete(pathname):
    _sdk().delete_blob(pathname)


def probe():
    """Fast reachability check for readiness. Returns 'ok', 'access_denied' or 'unavailable'."""
    from vercel.blob.errors import BlobAccessError, BlobStoreNotFoundError, BlobStoreSuspendedError
    try:
        next(iter(_sdk().query_blobs(page_size=1)), None)
        return 'ok'
    except (BlobAccessError, BlobStoreNotFoundError, BlobStoreSuspendedError):
        return 'access_denied'
    except Exception:
        return 'unavailable'


def client_token(pathname, content_type, max_bytes, ttl, now_ms=None, rw_token=None):
    """Permission for one browser upload: this pathname, this content type, at most max_bytes, until the token expires."""
    t = token() if rw_token is None else rw_token
    valid_until = int((time.time() * 1000 if now_ms is None else now_ms) + ttl * 1000)
    payload = base64.b64encode(json.dumps({'pathname': pathname, 'allowedContentTypes': [content_type], 'maximumSizeInBytes': int(max_bytes),
                                           'addRandomSuffix': False, 'allowOverwrite': False, 'validUntil': valid_until},
                                          separators=(',', ':')).encode()).decode()
    signature = hmac.new(t.encode(), payload.encode(), hashlib.sha256).hexdigest()
    return f'vercel_blob_client_{store_id(t)}_' + base64.b64encode(f'{signature}.{payload}'.encode()).decode()


def _read_delegation():
    """A read-only signing delegation for the whole store, reused for 50 minutes so playback does not call the API each time."""
    with _lock:
        d = _delegation.get('get')
        if d and d['refresh_at'] > time.time(): return d
    r = httpx.post(f'{api_url()}/signed-token', timeout=10,
                   headers={'authorization': f'Bearer {token()}', 'x-api-version': API_VERSION, 'content-type': 'application/json'},
                   json={'operations': ['get'], 'validUntil': int((time.time() + 3600) * 1000)})
    r.raise_for_status()
    d = {**r.json(), 'refresh_at': time.time() + 3000}
    with _lock: _delegation['get'] = d
    return d


def reset():
    with _lock: _delegation.clear()


def sign_read(pathname, delegation_token, signing_token, valid_until_ms):
    """Query parameters of a signed GET: an HMAC over the operation, pathname and expiry, sorted as the SDK sorts them."""
    expiry = str(int(valid_until_ms))
    lines = sorted(['operation=get', f'pathname={pathname}', f'vercel-blob-valid-until={expiry}'], key=lambda s: s.encode())
    mac = hmac.new(signing_token.encode(), '\n'.join(lines).encode(), hashlib.sha256).digest()
    return {'vercel-blob-valid-until': expiry, 'vercel-blob-delegation': delegation_token,
            'vercel-blob-signature': base64.urlsafe_b64encode(mac).decode().rstrip('=')}


def signed_url(pathname, ttl, download=False):
    """Short-lived link to a private object, opened by the browser after every access check has passed."""
    d = _read_delegation()
    params = sign_read(pathname, d['delegationToken'], d['clientSigningToken'], (time.time() + ttl) * 1000)
    if download: params = {'download': '1', **params}
    return f'{delivery_url(pathname)}?{urlencode(params)}'
